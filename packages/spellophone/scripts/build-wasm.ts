// Builds wasm/espeak-ng.{js,wasm,d.ts} from the vendored espeak-ng sources
// and native/glue.c with Emscripten (see native/CMakeLists.txt), plus the
// legacy build's wasm/espeak-ng.legacy.js and wasm/espeak-ng.legacy.wasm.js.
//
//   pnpm --filter @spelling-creator/spellophone build:wasm
//
// Requires emcmake/emcc (the emsdk) and cmake on the PATH. mise.toml pins the
// emsdk version this was developed against.

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { paths, run } from "./paths.ts";

if (!existsSync(join(paths.espeakRoot, "CMakeLists.txt"))) {
  console.error("espeak-ng sources not found. Run `pnpm fetch:espeak` first.");
  process.exit(1);
}

const buildDir = join(paths.buildRoot, "wasm");

run("emcmake", [
  "cmake",
  "-S",
  paths.nativeDir,
  "-B",
  buildDir,
  "-DCMAKE_BUILD_TYPE=Release",
  `-DESPEAK_ROOT=${paths.espeakRoot}`,
  `-DSPELLOPHONE_OUTPUT_DIR=${paths.wasmDir}`,
]);
run("cmake", ["--build", buildDir, "--parallel"]);

// The legacy module: the glue as Emscripten wrote it, and the wasm turned
// into JavaScript by Binaryen's wasm2js, which ships with the emsdk.
const legacyDir = join(buildDir, "legacy");
copyFileSync(
  join(legacyDir, "espeak-ng.legacy.js"),
  join(paths.wasmDir, "espeak-ng.legacy.js"),
);

const binaryenRoot = execFileSync("em-config", ["BINARYEN_ROOT"], {
  encoding: "utf8",
}).trim();
const wasm2jsOutput = join(legacyDir, "espeak-ng.legacy.wasm2js.js");
run(join(binaryenRoot, "bin", "wasm2js"), [
  join(legacyDir, "espeak-ng.legacy.wasm"),
  "-o",
  wasm2jsOutput,
  "-O",
  // In emscripten-compatible form wasm2js writes a single
  // `function instantiate(imports)` that returns the module's exports.
  "--emscripten",
  // The wasm uses these, and the optimized binary no longer records which
  // features it was compiled with. wasm2js lowers all of them.
  "--enable-bulk-memory",
  "--enable-bulk-memory-opt",
  "--enable-nontrapping-float-to-int",
  "--enable-sign-ext",
  "--enable-mutable-globals",
]);
writeFileSync(
  join(paths.wasmDir, "espeak-ng.legacy.wasm.js"),
  `// espeak-ng.legacy.wasm compiled to JavaScript by Binaryen's wasm2js.\n` +
    `// Generated by scripts/build-wasm.ts.\n` +
    readFileSync(wasm2jsOutput, "utf8") +
    `export default instantiate;\n`,
);

// Emscripten's --emit-tsd only works for the wasm build, and the legacy
// module has the same exports anyway, so its declarations are written here.
writeFileSync(
  join(paths.wasmDir, "espeak-ng.legacy.d.ts"),
  `// Generated by scripts/build-wasm.ts.
import type { MainModule } from "./espeak-ng.js";

/** Hands the glue the module's exports in place of a WebAssembly instance. */
export type InstantiateWasm = (
  imports: object,
  receiveInstance: (instance: { exports: object }) => void,
) => object;

/**
 * The wasm module's runtime, minus NODEFS: the legacy glue is for browsers
 * and workers only, so it is not linked in.
 */
export type LegacyModule = Omit<MainModule, "NODEFS">;

export default function createEspeakModule(options?: {
  print?: (line: string) => void;
  printErr?: (line: string) => void;
  instantiateWasm?: InstantiateWasm;
}): Promise<LegacyModule>;
`,
);
writeFileSync(
  join(paths.wasmDir, "espeak-ng.legacy.wasm.d.ts"),
  `// Generated by scripts/build-wasm.ts.
/** Instantiates the module from its imports and returns its exports. */
export default function instantiate(imports: object): object;
`,
);

console.log(`wasm modules ready in ${paths.wasmDir}`);
